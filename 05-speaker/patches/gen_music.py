import struct, math, wave, os, sys
sys.stdout.reconfigure(encoding='utf-8', errors='replace')

N = {'C4':261.63,'D4':293.66,'E4':329.63,'F4':349.23,'G4':392.00,'A4':440.00,'B4':493.88,
     'C5':523.25,'D5':587.33,'E5':659.25,'G3':196.00,'A3':220.00,'C3':130.81,'G5':783.99,'F5':698.46}

def gen(path, song, rate=44100, tempo=1.0):
    data = bytearray()
    for note, dur in song:
        if note is None:            # 休止符
            n = int(rate*dur*tempo)
            data += b'\x00\x00' * n
            continue
        f = N[note]; n = int(rate*dur*tempo)
        for i in range(n):
            t = i/rate
            env = 1.0
            if i < rate*0.012: env = i/(rate*0.012)
            elif i > n - rate*0.06: env = (n-i)/(rate*0.06)
            # 基频+泛音：更饱满，像八音盒
            v = (1.0*math.sin(2*math.pi*f*t)
                 + 0.35*math.sin(2*math.pi*2*f*t)
                 + 0.12*math.sin(2*math.pi*3*f*t))
            data += struct.pack('<h', int(32767*0.32*env*v/1.47))
    with wave.open(path,'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate)
        w.writeframes(bytes(data))
    return os.path.getsize(path)

